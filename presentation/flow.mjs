import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 2 });
page.on('pageerror', (e) => console.log('pageerror:', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('console error:', m.text().slice(0,200)); });
await page.goto('http://localhost:5173/#/');
await page.waitForTimeout(1500);
await page.evaluate(() => window.dispatchEvent(new CustomEvent('zk:locate', { detail: { lat: 56.9692, lon: 23.7787, zoom: 17 } })));
await page.waitForTimeout(3500);
await page.mouse.click(520, 520);
await page.waitForTimeout(12000);
await page.screenshot({ path: 'shots/flow1.png' });
await page.locator('.panel-scroll').evaluate((el) => { el.scrollTop = el.scrollHeight; });
await page.waitForTimeout(600);
await page.screenshot({ path: 'shots/flow2.png' });
await page.fill('#company-reg', '40003032949');
await page.click('.company .btn');
await page.waitForTimeout(12000);
await page.locator('.panel-scroll').evaluate((el) => { el.scrollTop = el.scrollHeight; });
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/flow3.png' });
await browser.close();
